/* ============================================================
   Skill catalogue
   ---------------
   What PixGPT can do, described once, in terms of the systems that
   actually implement it.

   Every skill names the tools it needs from the existing tool registry
   and the requirements that must resolve before it is offered. Nothing
   here implements a capability — a skill is a declaration that binds
   an intent to machinery that already exists.

   `permission` is the ceiling, not a grant. A skill listing an
   approval-gated tool does not thereby gain approval; the command
   classifier still decides at execution time. A skill can never widen
   its own permissions.
   ============================================================ */

