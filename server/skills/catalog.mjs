/**
 * A skill:
 *   id, name, description, category, icon
 *   requires[]   requirement ids that must resolve
 *   tools[]      tool-registry names it needs
 *   permission   the ceiling for what it may do
 *   match[]      patterns that suggest it for a request
 *   settings{}   user-adjustable configuration
 *   mode         which product mode it belongs to
 */
